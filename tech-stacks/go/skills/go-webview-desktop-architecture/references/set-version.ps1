#Requires -Version 5.1
<#
Reference copy, from the toolkit's go-webview-desktop-architecture skill: copy it to scripts/set-version.ps1.
It assumes the standard `wails3 init` build/ tree and nothing else, so it should need no edit.

One version for the whole build. The source of truth is `version:` in build/config.yml.

  scripts/set-version.ps1 X.Y.Z[-pre]  writes it into build/config.yml and every other place that carries it
                                       (listed in Get-VersionTargets below)
  scripts/set-version.ps1 -Check       fails when one of them differs from build/config.yml, or when
                                       windows/info.json's FileDescription is not the product name
  scripts/set-version.ps1 -SelfTest    proves the check on a throw-away copy: set, check green, corrupt one
                                       target, check red. Nothing in the repository is modified.

Why a script: the installer's version comes from the default in build/windows/nsis/wails_tools.nsh and the
exe's from windows/info.json, both generated by `wails3 task common:update:build-assets`. Editing
config.yml alone would ship the previous version in Add/Remove Programs and file Properties with
nothing to say so. scripts/check.ps1 and scripts/package.ps1 run -Check; package.ps1 also reads the
version back from the built installer and exe.

FileDescription is what Task Manager shows as the process name, so it must be the app's name; the
generator rewrites it from `description`, which is why the check watches it.

Every target is required: a missing one is reported as drift.
Windows PowerShell 5.1 compatible (no ternary, no `&&`).
#>
[CmdletBinding(DefaultParameterSetName = 'Set')]
param(
    [Parameter(Position = 0, ParameterSetName = 'Set')][string]$Version,
    [Parameter(ParameterSetName = 'Check')][switch]$Check,
    [Parameter(ParameterSetName = 'SelfTest')][switch]$SelfTest,
    [string]$Root
)

$ErrorActionPreference = 'Stop'
if (-not $Root) { $Root = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path) }
$semver = '^\d+\.\d+\.\d+(-[0-9A-Za-z.-]+)?$'
$sourcePath = 'build/config.yml'
$sourcePattern = '(?m)^(  version: ")([^"]+)(")'

# One entry per file: relative path, a regex whose group 2 is the version, and how many times it must match.
function Get-VersionTargets {
    $win = '(?m)^(\s*"(?:file_version|product_version|FileVersion|ProductVersion)": ")([^"]+)(")'
    return @(
        @{ Path = $sourcePath; Pattern = $sourcePattern; Count = 1 },
        @{ Path = 'build/windows/info.json'; Pattern = $win; Count = 4 },
        # What the installer falls back to for Add/Remove Programs and its downgrade guard.
        @{ Path = 'build/windows/nsis/wails_tools.nsh'; Pattern = '(?m)^(\s*!define INFO_PRODUCTVERSION ")([^"]+)(")'; Count = 1 },
        # The application's own identity, not the Common-Controls dependency listed below it. A suffixed
        # version ("1.0.0-beta.1") is not a valid assembly version (four numbers): if Windows refuses to
        # start a pre-release build, drop this entry rather than the suffix.
        @{ Path = 'build/windows/wails.exe.manifest'; Pattern = '(<assemblyIdentity type="win32" name="(?!Microsoft\.)[^"]*" version=")([^"]+)(")'; Count = 1 }
    )
}

function Read-Raw([string]$path) { return [System.IO.File]::ReadAllText($path) }

# Writes text without a BOM and without touching line endings.
function Write-Raw([string]$path, [string]$text) {
    [System.IO.File]::WriteAllText($path, $text, (New-Object System.Text.UTF8Encoding($false)))
}

function Get-SourceVersion([string]$root) {
    $m = [regex]::Match((Read-Raw (Join-Path $root $sourcePath)), $sourcePattern)
    if (-not $m.Success) { throw "$sourcePath has no version field" }
    return $m.Groups[2].Value
}

function Set-AllVersions([string]$root, [string]$version) {
    if ($version -notmatch $semver) { throw "not a version: '$version' (expected X.Y.Z or X.Y.Z-beta.N)" }
    foreach ($t in Get-VersionTargets) {
        $file = Join-Path $root $t.Path
        if (-not (Test-Path -LiteralPath $file)) { throw "missing: $($t.Path)" }
        $text = Read-Raw $file
        $found = [regex]::Matches($text, $t.Pattern).Count
        if ($found -ne $t.Count) { throw "$($t.Path): expected $($t.Count) version field(s), found $found" }
        $new = [regex]::Replace($text, $t.Pattern, { param($m) $m.Groups[1].Value + $version + $m.Groups[3].Value })
        if ($new -ne $text) { Write-Raw $file $new }
        Write-Host "  $($t.Path) -> $version"
    }
}

# Returns the list of divergences (empty when everything is consistent).
function Get-Drift([string]$root) {
    $expected = Get-SourceVersion $root
    $drift = @()
    foreach ($t in Get-VersionTargets) {
        $file = Join-Path $root $t.Path
        if (-not (Test-Path -LiteralPath $file)) { $drift += "$($t.Path): file is missing"; continue }
        $found = [regex]::Matches((Read-Raw $file), $t.Pattern)
        if ($found.Count -ne $t.Count) {
            $drift += "$($t.Path): expected $($t.Count) version field(s), found $($found.Count)"
            continue
        }
        foreach ($m in $found) {
            if ($m.Groups[2].Value -ne $expected) { $drift += "$($t.Path): $($m.Groups[2].Value) (config.yml is $expected)" }
        }
    }
    $product = [regex]::Match((Read-Raw (Join-Path $root $sourcePath)), '(?m)^  productName: "([^"]+)"')
    $desc = [regex]::Match((Read-Raw (Join-Path $root 'build/windows/info.json')), '(?m)^\s*"FileDescription": "([^"]*)"')
    if (-not $product.Success -or -not $desc.Success) {
        $drift += 'productName (config.yml) or FileDescription (info.json) not found'
    }
    elseif ($product.Groups[1].Value -ne $desc.Groups[1].Value) {
        $drift += "build/windows/info.json: FileDescription is '$($desc.Groups[1].Value)', Task Manager would show it as the process name: it must be '$($product.Groups[1].Value)'"
    }
    return $drift
}

function Invoke-Check([string]$root) {
    $drift = @(Get-Drift $root)
    if ($drift.Count -gt 0) {
        Write-Host "FAILED: the build metadata is inconsistent (version $(Get-SourceVersion $root) in build/config.yml):" -ForegroundColor Red
        $drift | ForEach-Object { Write-Host "  $_" -ForegroundColor Red }
        return $false
    }
    Write-Host "All versions equal $(Get-SourceVersion $root); FileDescription is the product name." -ForegroundColor Green
    return $true
}

if ($SelfTest) {
    $tmp = Join-Path ([System.IO.Path]::GetTempPath()) ("set-version-selftest-" + [guid]::NewGuid().ToString('N'))
    try {
        foreach ($t in Get-VersionTargets) {
            $dst = Join-Path $tmp $t.Path
            New-Item -ItemType Directory -Force -Path (Split-Path -Parent $dst) | Out-Null
            Copy-Item -LiteralPath (Join-Path $Root $t.Path) -Destination $dst
        }
        Set-AllVersions $tmp '9.8.7-beta.1'
        if (-not (Invoke-Check $tmp)) { Write-Host 'SELF-TEST FAILED: check is red right after set.' -ForegroundColor Red; exit 1 }
        $victim = Join-Path $tmp 'build/windows/info.json'
        $good = Read-Raw $victim
        Write-Raw $victim ($good -replace '"ProductVersion": "9.8.7-beta.1"', '"ProductVersion": "9.8.6"')
        Write-Host '(the next failure is expected)'
        if (Invoke-Check $tmp) { Write-Host 'SELF-TEST FAILED: check did not see a diverging target.' -ForegroundColor Red; exit 1 }
        Write-Raw $victim ($good -replace '"FileDescription": "[^"]*"', '"FileDescription": "A tagline"')
        Write-Host '(and the next one)'
        if (Invoke-Check $tmp) { Write-Host 'SELF-TEST FAILED: check did not see a FileDescription that is not the product name.' -ForegroundColor Red; exit 1 }
        Write-Host 'Self-test passed: set then check is green, a diverging version and a wrong FileDescription are caught.' -ForegroundColor Green
        exit 0
    }
    finally {
        if (Test-Path $tmp) { Remove-Item -Recurse -Force $tmp }
    }
}

if ($Check) {
    if (-not (Invoke-Check $Root)) { exit 1 }
    exit 0
}

if (-not $Version) {
    Write-Host 'usage: set-version.ps1 X.Y.Z[-pre] | -Check | -SelfTest' -ForegroundColor Red
    exit 2
}
Write-Host "Setting version $Version" -ForegroundColor Cyan
Set-AllVersions $Root $Version
if (-not (Invoke-Check $Root)) { exit 1 }
